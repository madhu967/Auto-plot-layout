export function getPadamFromVarga(ownerName) {
  if (!ownerName || ownerName.trim().length === 0) {
    return TELUGU_VARGA[7]; // Default fallback
  }
  const firstLetter = ownerName.trim().charAt(0);
  
  // Find which list matches the letter
  for (const varga of TELUGU_VARGA) {
    const lettersList = varga.letters.split(",").map(l => l.trim());
    if (lettersList.some(l => firstLetter === l || firstLetter.includes(l))) {
      return varga;
    }
  }
  
  // Check if first letter is Telugu or English character
  const isTelugu = /[\u0C00-\u0C7F]/.test(firstLetter);
  if (isTelugu) {
    // Try to match basic vowels/consonants
    const match = TELUGU_VARGA.find(v => v.letters.includes(firstLetter));
    if (match) return match;
  }
  
  // English or unmatched fallback
  return TELUGU_VARGA[7];
}

export function validateOpenSpace(east, west, north, south) {
  const e = parseFloat(east) || 0;
  const w = parseFloat(west) || 0;
  const n = parseFloat(north) || 0;
  const s = parseFloat(south) || 0;
  
  const errors = [];
  const warnings = [];
  
  // East space should be more than West space
  if (e <= w) {
    warnings.push({
      en: "East space should ideally be larger than West space.",
      te: "తూర్పు ఖాళీ స్థలం పడమర కంటే ఎక్కువగా ఉండాలి."
    });
  }
  // North space should be more than South space
  if (n <= s) {
    warnings.push({
      en: "North space should ideally be larger than South space.",
      te: "ఉత్తర ఖాళీ స్థలం దక్షిణం కంటే ఎక్కువగా ఉండాలి."
    });
  }
  
  if (e < 1 || w < 1 || n < 1 || s < 1) {
    errors.push({
      en: "Minimum 1 ft setback space is recommended on all sides.",
      te: "అన్ని వైపులా కనీసం 1 అడుగు ఖాళీ స్థలం (setback) ఉండాలి."
    });
  }
  
  return {
    isValid: errors.length === 0,
    errors,
    warnings,
    status: errors.length > 0 ? "danger" : warnings.length > 0 ? "warning" : "success"
  };
}

